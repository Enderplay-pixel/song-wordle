export interface Song {
  id: string;
  title: string;
  artist: string;
  youtubeId: string;       // verified, plays in Germany
  startOffset: number;     // seconds — where the snippet starts (0 = song start)
  searchTerms: string[];
  category?: string;       // filter group; defaults to artist if unset
}

// Primary group (artist, or explicit category like "Charts").
export const songCategory = (s: Song): string => s.category ?? s.artist;

